import { z } from 'zod';
import { stringify } from 'yaml';

const rule = z.object({ path: z.string().trim().min(1, 'Add a path for each instruction.'), instructions: z.string().trim().min(1, 'Explain what to check for each path.').max(20000) });
const guideline = z.object({ files: z.string().trim().min(1, 'Add a guideline source.'), applyTo: z.string().trim() });
const linked = z.object({ repository: z.string().trim().regex(/^[^\s/:]+(?:\/[^\s/:]+)+$/, 'Use a repository path such as org/repo or group/subgroup/repo.'), instructions: z.string().trim().max(2000) });

export const answersSchema = z.object({
  repository: z.string().max(200),
  inheritance: z.boolean(),
  profile: z.enum(['quiet', 'chill', 'assertive']),
  tone: z.string().max(250, 'Tone must be 250 characters or fewer.'),
  pathFilters: z.string().max(20000),
  pathInstructions: z.array(rule).max(100),
  guidelinesEnabled: z.boolean(),
  guidelines: z.array(guideline).max(50),
  linkedRepositories: z.array(linked).max(20),
  autoReview: z.boolean(),
  drafts: z.boolean(),
  incremental: z.boolean(),
  baseBranches: z.string().max(2000),
  summary: z.boolean(),
  sequenceDiagrams: z.boolean(),
  poem: z.boolean(),
  autoReply: z.boolean(),
  webSearch: z.boolean(),
});
export type Answers = z.infer<typeof answersSchema>;
export const defaults: Answers = {
  repository: '', inheritance: true, profile: 'chill',
  tone: 'Be concise, constructive, and specific. Explain the impact of each issue and suggest a concrete fix.',
  pathFilters: '', pathInstructions: [], guidelinesEnabled: true, guidelines: [], linkedRepositories: [],
  autoReview: true, drafts: false, incremental: true, baseBranches: '',
  summary: true, sequenceDiagrams: false, poem: false, autoReply: true, webSearch: true,
};
export const lines = (text: string) => [...new Set(text.split('\n').map(s => s.trim()).filter(Boolean))];

/** Deliberately generates only settings exposed by the questionnaire. */
export function buildConfig(input: Answers) {
  const a = answersSchema.parse(input);
  const paths = lines(a.pathFilters);
  const branches = lines(a.baseBranches);
  return {
    inheritance: a.inheritance,
    tone_instructions: a.tone,
    reviews: {
      profile: a.profile,
      high_level_summary: a.summary,
      sequence_diagrams: a.sequenceDiagrams,
      poem: a.poem,
      ...(paths.length ? { path_filters: paths } : {}),
      ...(a.pathInstructions.length ? { path_instructions: a.pathInstructions } : {}),
      auto_review: {
        enabled: a.autoReview,
        drafts: a.drafts,
        auto_incremental_review: a.incremental,
        ...(branches.length ? { base_branches: branches } : {}),
      },
    },
    chat: { auto_reply: a.autoReply },
    knowledge_base: {
      web_search: { enabled: a.webSearch },
      code_guidelines: {
        enabled: a.guidelinesEnabled,
        ...(a.guidelinesEnabled && a.guidelines.length ? { filePatterns: a.guidelines.map(g => g.applyTo ? g : g.files) } : {}),
      },
      ...(a.linkedRepositories.length ? { linked_repositories: a.linkedRepositories } : {}),
    },
  };
}
export function generateYaml(input: Answers) {
  return '# yaml-language-server: $schema=https://coderabbit.ai/integrations/schema.v2.json\n'
    + '# Generated by Rabbit Config. Review before committing to your repository.\n'
    + stringify(buildConfig(input), { lineWidth: 100 });
}

const DRAFT_KEY = 'rabbit-config:draft:v1';
// In-progress rows are allowed in storage even when export validation rejects them.
const draftSchema = answersSchema.extend({
  pathInstructions: z.array(z.object({ path: z.string().max(2000), instructions: z.string().max(20000) })).max(100),
  guidelines: z.array(z.object({ files: z.string().max(2000), applyTo: z.string().max(2000) })).max(50),
  linkedRepositories: z.array(z.object({ repository: z.string().max(2000), instructions: z.string().max(2000) })).max(20),
});
export function readDraft(storage: Pick<Storage, 'getItem'>): Answers {
  try {
    const raw = storage.getItem(DRAFT_KEY);
    if (!raw || raw.length > 1_000_000) return structuredClone(defaults);
    const result = draftSchema.safeParse(JSON.parse(raw));
    return result.success ? result.data : structuredClone(defaults);
  } catch { return structuredClone(defaults); }
}
export function saveDraft(storage: Pick<Storage, 'setItem'>, answers: Answers): boolean {
  try { storage.setItem(DRAFT_KEY, JSON.stringify(answers)); return true; } catch { return false; }
}
