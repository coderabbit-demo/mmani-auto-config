import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const root = new URL('../', import.meta.url);
const schemaPath = new URL('schemas/coderabbit.schema.json', root);
const metaPath = new URL('schemas/coderabbit.schema.meta.json', root);
const mode = process.argv[2] ?? 'verify';
const source = 'https://coderabbit.ai/integrations/schema.v2.json';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

function verifyShape(schema) {
  // Detect a stale document or a non-schema response before replacing the pin.
  if (schema.$schema !== 'https://json-schema.org/draft/2020-12/schema'
    || !schema.properties?.reviews?.properties?.profile?.enum?.includes('quiet')
    || !schema.properties?.inheritance
    || !schema.properties?.knowledge_base?.properties?.code_guidelines?.properties?.filePatterns?.items?.anyOf?.some(x => x.type === 'object')
    || !schema.properties?.knowledge_base?.properties?.linked_repositories) {
    throw new Error('Unexpected official schema shape. Inspect upstream changes before updating.');
  }
  return new Ajv2020({ allErrors: true, strict: false, code: { source: true } }).compile(schema);
}

let bytes = await readFile(schemaPath);
let meta = JSON.parse(await readFile(metaPath, 'utf8'));
if (mode === 'update') {
  const response = await fetch(source, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok || !['coderabbit.ai', 'www.coderabbit.ai'].includes(new URL(response.url).hostname)
    || !response.headers.get('content-type')?.includes('application/json')) {
    throw new Error('Could not retrieve JSON from the official CodeRabbit schema endpoint. Pin unchanged.');
  }
  const next = Buffer.from(await response.arrayBuffer());
  verifyShape(JSON.parse(next));
  const now = new Date();
  meta = { source, resolvedSource: response.url, retrievedAt: now.toISOString(),
    verifiedOn: now.toLocaleDateString('en-CA', { timeZone: 'America/Los_Angeles' }),
    dialect: JSON.parse(next).$schema, sha256: hash(next), etag: response.headers.get('etag'),
    lastModified: response.headers.get('last-modified') };
  await writeFile(schemaPath, next);
  await writeFile(metaPath, JSON.stringify(meta, null, 2) + '\n');
  bytes = next;
}
if (hash(bytes) !== meta.sha256 || meta.source !== source) throw new Error('Schema pin hash/source mismatch.');
const schema = JSON.parse(bytes);
verifyShape(schema);
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
const validate = ajv.compile(schema);
const result = await build({ stdin: { contents: standaloneCode(ajv, validate), resolveDir: fileURLToPath(root) },
  bundle: true, format: 'esm', platform: 'browser', minify: true, write: false });
const generated = `// Generated by npm run schema:generate; schema SHA-256 ${meta.sha256}\n${result.outputFiles[0].text}`;
const output = new URL('src/generated/schema-validator.js', root);
if (mode === 'verify') {
  if (await readFile(output, 'utf8') !== generated) throw new Error('Generated validator is stale. Run npm run schema:generate.');
} else if (['generate', 'update'].includes(mode)) {
  await mkdir(new URL('src/generated/', root), { recursive: true });
  await writeFile(output, generated);
} else throw new Error('Use verify, generate, or update.');
console.log(`Official CodeRabbit schema verified: ${meta.sha256}`);
